import { chromium } from 'playwright';
import { choose } from './choose.js';
import assert from 'node:assert/strict';
import { createServer } from '../collector/server.js';
import { demoData } from '../src/demo.js';
import { resolve } from 'node:path';
const token = 'fixture-capability-not-a-real-credential';
let config = { interval: 300, autoCodex: true, autoDsh: true, scanTokens: true, accounts: [] };
const svc = createServer({ token, root: resolve('wallpaper'), getSnapshot: () => demoData(), getConfig: () => ({ ...config, accounts: config.accounts.map(({ apiKey, ...a }) => ({ ...a, apiKeyConfigured: !!apiKey })) }), setConfig: async c => { config = c; }, collect: async () => {} });
await new Promise(r => svc.listen(0,'127.0.0.1',r));
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || (process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : undefined), headless: true });
try {
  const page = await browser.newPage();
  await page.goto(`http://127.0.0.1:${svc.address().port}/#bridge=${token}`);
  await page.locator('.account-card').first().waitFor();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.getByRole('button',{name:'数据与账号',exact:true}).click();
  await page.locator('#auto-codex').waitFor();
  await page.locator('#add-account').click();
  await page.locator('#account-0-name').fill('共享钱包');
  await page.locator('#account-0-groupId').fill('same-account');
  await page.locator('#account-0-apiKey').fill('fixture-key-one');
  await page.locator('#add-account').click();
  await page.locator('#account-1-name').fill('第二个 key');
  await page.locator('#account-1-groupId').fill('same-account');
  await page.locator('#account-1-apiKey').fill('fixture-key-two');
  await page.locator('#save-accounts').click();
  await page.getByText('账号已保存并刷新。',{exact:true}).waitFor();
  assert.equal(config.accounts.length,2);
  assert.equal(config.accounts[0].groupId,'same-account');
  assert.equal(config.accounts[1].apiKey,'fixture-key-two');
  assert.equal(await page.locator('#account-0-apiKey').inputValue(),'');
  const download = page.waitForEvent('download');
  await page.locator('#export-config').click();
  const file = await download;
  const { readFile } = await import('node:fs/promises');
  const exported = await readFile(await file.path(),'utf8');
  assert.equal(exported.includes(token),false); assert.equal(exported.includes('fixture-key'),false);
  await choose(page, 'add-provider', 'codex'); await page.locator('#add-account').click();
  await page.locator('#account-2-codexHome').fill('C:/isolated-codex-home');
  await page.locator('#account-2-plan').fill('Pro');
  await page.locator('#save-accounts').click();
  await page.waitForFunction(() => document.querySelector('#account-2-plan')?.value === 'Pro');
  assert.equal(config.accounts[2].codexHome,'C:/isolated-codex-home');
  console.log('Bridge UI passed: multiple keys, shared groups, independent Codex homes, masked keys and secret-free export.');
} finally { await browser.close(); await new Promise(r=>svc.close(r)); }
